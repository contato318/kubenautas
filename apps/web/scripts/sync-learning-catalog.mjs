import { createServer } from 'vite';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createServer as createHttpServer } from 'node:http';

const httpServer = createHttpServer();
const server = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { middlewareMode: true, hmr: { server: httpServer } }, appType: 'custom' });
try {
  const { modules } = await server.ssrLoadModule('/src/content/modules.ts');
  const { cases } = await server.ssrLoadModule('/src/content/cases.ts');
  const { simulators } = await server.ssrLoadModule('/src/components/simulators/registry.ts');
  const catalog = {
    modules: modules.map(module => ({ id: module.id, title: module.title, lessons: module.lessons.map(lesson => ({ key: `${module.id}/${lesson.slug}`, title: lesson.title })) })),
    cases: cases.map(item => ({ id: item.slug, title: item.title })),
    simulators: simulators.map(item => ({ id: item.id, title: item.title })),
  };
  await writeFile(new URL('../../../packages/contracts/src/learning-catalog.ts', import.meta.url), `// Generated by pnpm --filter @jack-academy/web catalog. Do not edit by hand.\nexport const learningCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n`);
  console.log(`Catalog synchronized: ${catalog.modules.reduce((sum, module) => sum + module.lessons.length, 0)} lessons.`);
} finally { await server.close(); }
